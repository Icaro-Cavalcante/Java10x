package construtores;

public class Hokage {
    String nome;
    int idade;
    Boolean vivo_ou_nao;
    String poderes;
    String cla;

    public Hokage(String nome, int idade, Boolean vivo_ou_nao, String poderes, String cla) {
        this.nome = nome;
        this.idade = idade;
        this.vivo_ou_nao = vivo_ou_nao;
        this.poderes = poderes;
        this.cla = cla;
    }
}

